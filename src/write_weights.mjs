// Writes docs/decoder-weights.js from the tuned weights in results/ (run after eval_decoder / eval_commands).
import fs from 'fs';
const read = p => fs.existsSync(p) ? JSON.parse(fs.readFileSync(p)) : {};
const general = read('results/decoder_weights.json');
const dom = read('results/decoder_commands.json').domainWeights || { domain: 6 };
fs.writeFileSync('docs/decoder-weights.js', `// Generated by src/write_weights.mjs from results/ — tuned on dev splits only.\nexport const DECODER_WEIGHTS = ${JSON.stringify(general)};\nexport const DOMAIN_WEIGHTS = ${JSON.stringify(dom)};\n`);
console.log(fs.readFileSync('docs/decoder-weights.js', 'utf8'));
